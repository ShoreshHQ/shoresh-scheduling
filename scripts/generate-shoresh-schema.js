#!/usr/bin/env node
/**
 * Writes force-app/main/default/lwc/shoreshSchema/shoreshSchema.js from the object metadata:
 * one `@salesforce/schema` import per custom object and field, so the screens get every name
 * with the package namespace already on it. Run it after adding or removing an object or field:
 *
 *   node scripts/generate-shoresh-schema.js           write the file
 *   node scripts/generate-shoresh-schema.js --check   exit 1 if the committed file is out of date
 *
 * A Jest test (lwc/shoreshSchema/__tests__) runs --check.
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OBJECTS = path.join(ROOT, "force-app/main/default/objects");
const OUTPUT = path.join(
  ROOT,
  "force-app/main/default/lwc/shoreshSchema/shoreshSchema.js"
);

function tag(xml, name) {
  const m = xml.match(new RegExp(`<${name}>([^<]*)</${name}>`));
  return m ? m[1].trim() : null;
}

/** [{ object: "Week__c", fields: [{ name, relationshipName, referenceTo }] }], sorted. */
function readObjects(dir = OBJECTS) {
  return fs
    .readdirSync(dir)
    .filter((o) => o.endsWith("__c"))
    .sort()
    .map((object) => {
      const fieldsDir = path.join(dir, object, "fields");
      const files = fs.existsSync(fieldsDir)
        ? fs.readdirSync(fieldsDir).sort()
        : [];
      const fields = files
        .filter((f) => f.endsWith(".field-meta.xml"))
        .map((f) => {
          const xml = fs.readFileSync(path.join(fieldsDir, f), "utf8");
          return {
            name: tag(xml, "fullName"),
            referenceTo: tag(xml, "referenceTo"),
            relationshipName: tag(xml, "relationshipName")
          };
        })
        .filter((f) => f.name && f.name.endsWith("__c"));
      return { object, fields };
    });
}

const bare = (apiName) => apiName.replace(/__c$/, "");
const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);

function render(objects = readObjects()) {
  const lines = [];
  const used = new Set();
  const ident = (name) => {
    if (used.has(name)) throw new Error(`Duplicate import name ${name}`);
    used.add(name);
    return name;
  };
  const objectIds = {};
  const fieldIds = {};
  for (const { object, fields } of objects) {
    objectIds[object] = ident(`${lowerFirst(bare(object))}Object`);
    lines.push(
      `import ${objectIds[object]} from "@salesforce/schema/${object}";`
    );
    for (const f of fields) {
      const id = ident(`${lowerFirst(bare(object))}${bare(f.name)}`);
      fieldIds[`${object}.${f.name}`] = id;
      lines.push(`import ${id} from "@salesforce/schema/${object}.${f.name}";`);
    }
  }
  const first = objects[0].object;
  const out = [];
  out.push(
    "/**",
    " * GENERATED by scripts/generate-shoresh-schema.js from the object metadata. Do not edit by hand:",
    " * run `node scripts/generate-shoresh-schema.js` after adding or removing an object or field.",
    " *",
    " * The one place screens get object, field and relationship names. Salesforce adds the package",
    " * namespace to these imports (`shoresh__StartDate__c` once it has one), so records read and",
    " * saved with them keep working when the namespace arrives. Elsewhere, never spell a name as",
    " * text: scripts/namespace-safety.js counts those spellings and CI fails if any file gains one.",
    " *",
    ' *   import { FIELD, OBJECT } from "c/shoreshSchema";',
    " *   week[FIELD.Week.StartDate]          // not week.StartDate__c",
    ' *   { sobjectType: OBJECT.Week, ... }   // not "Week__c"',
    " */",
    ...lines,
    "",
    '/** What Salesforce puts before every name in this package: "" today, "shoresh__" later. */',
    `export const NAMESPACE_PREFIX = ${objectIds[first]}.objectApiName.slice(`,
    `  0,`,
    `  -"${first}".length`,
    ");",
    "",
    "/** Object names: OBJECT.Week. */",
    "export const OBJECT = Object.freeze({"
  );
  for (const { object } of objects) {
    out.push(`  ${bare(object)}: ${objectIds[object]}.objectApiName,`);
  }
  out.push(
    "});",
    "",
    "/** Field names by object: FIELD.Week.StartDate. */",
    "export const FIELD = Object.freeze({"
  );
  for (const { object, fields } of objects) {
    if (!fields.length) {
      out.push(`  ${bare(object)}: Object.freeze({}),`);
      continue;
    }
    out.push(`  ${bare(object)}: Object.freeze({`);
    for (const f of fields) {
      out.push(
        `    ${bare(f.name)}: ${fieldIds[`${object}.${f.name}`]}.fieldApiName,`
      );
    }
    out.push("  }),");
  }
  out.push(
    "});",
    "",
    "/** A lookup's parent record on a read row: row[PARENT.Season.CopiedFrom].Name. */",
    "export const PARENT = Object.freeze({"
  );
  for (const { object, fields } of objects) {
    const lookups = fields.filter((f) => f.referenceTo);
    if (!lookups.length) continue;
    out.push(`  ${bare(object)}: Object.freeze({`);
    for (const f of lookups) {
      out.push(
        `    ${bare(f.name)}: FIELD.${bare(object)}.${bare(f.name)}.replace(/__c$/, "__r"),`
      );
    }
    out.push("  }),");
  }
  out.push(
    "});",
    "",
    "/** A parent's child rows on a read row: activity[CHILDREN.Activity.Eligibilities]. */",
    "export const CHILDREN = Object.freeze({"
  );
  const children = {};
  for (const { object, fields } of objects) {
    for (const f of fields) {
      if (f.referenceTo && f.relationshipName) {
        (children[f.referenceTo] = children[f.referenceTo] || []).push(
          f.relationshipName
        );
      }
    }
  }
  for (const parent of Object.keys(children).sort()) {
    out.push(`  ${bare(parent)}: Object.freeze({`);
    for (const rel of children[parent].sort()) {
      out.push(`    ${rel}: \`\${NAMESPACE_PREFIX}${rel}__r\`,`);
    }
    out.push("  }),");
  }
  out.push("});", "");
  return out.join("\n");
}

/** The file as committed: render() formatted with the repository's Prettier settings. */
async function renderFormatted(objects) {
  const prettier = require("prettier");
  const options = await prettier.resolveConfig(OUTPUT);
  return prettier.format(render(objects), { ...options, filepath: OUTPUT });
}

module.exports = { readObjects, render, renderFormatted };

if (require.main === module) {
  renderFormatted().then((text) => {
    const rel = path.relative(ROOT, OUTPUT);
    if (process.argv.includes("--check")) {
      const current = fs.existsSync(OUTPUT)
        ? fs.readFileSync(OUTPUT, "utf8")
        : "";
      if (current !== text) {
        console.error(
          `${rel} is out of date. Run: node scripts/generate-shoresh-schema.js`
        );
        process.exitCode = 1;
      }
      return;
    }
    fs.writeFileSync(OUTPUT, text);
    console.log(`Wrote ${rel}`);
  });
}
